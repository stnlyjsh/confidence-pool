<?php

namespace App\Console\Commands;

use App\Models\Game;
use App\Services\Espn\EspnScheduleSyncService;
use App\Services\PollingWindowGenerator;
use Illuminate\Console\Attributes\Description;
use Illuminate\Console\Attributes\Signature;
use Illuminate\Console\Command;

#[Signature('schedule:generate-polling-windows {--weeks-ahead=2}')]
#[Description('Regenerate routes/polling-windows.php from the real upcoming schedule, so tight polling only wakes the app when a game could plausibly be live')]
class GeneratePollingWindows extends Command
{
    public function handle(EspnScheduleSyncService $sync, PollingWindowGenerator $generator): int
    {
        // Seeds whatever ESPN considers "current" right now — needed even
        // on a totally empty database (e.g. a fresh CI run) so there's a
        // season/week to look ahead from at all.
        $sync->sync();

        $current = Game::currentWeek();

        if (! $current) {
            $this->warn('ESPN returned no current game data — nothing to generate windows from.');

            return self::SUCCESS;
        }

        $weeksAhead = (int) $this->option('weeks-ahead');

        for ($i = 1; $i <= $weeksAhead; $i++) {
            $sync->sync($current['season'], min($current['week'] + $i, 18));
        }

        $kickoffs = Game::query()
            ->where('kickoff_at', '>=', now()->subHours(6))
            ->where('kickoff_at', '<=', now()->addWeeks($weeksAhead + 1))
            ->get()
            ->reject($this->isUnconfirmed(...))
            ->pluck('kickoff_at');

        $expressions = $generator->generate($kickoffs);

        $this->writeWindowsFile($expressions);

        $this->info(count($expressions).' polling window(s) written to routes/polling-windows.php.');

        return self::SUCCESS;
    }

    /**
     * ESPN marks a game whose kickoff time hasn't been finalized yet (most
     * often Sunday Night Football flex slots in the back half of the
     * season) with a "TBD" status detail rather than a real time — those
     * shouldn't be trusted to generate a window.
     */
    private function isUnconfirmed(Game $game): bool
    {
        $detail = $game->raw_espn_payload['status']['type']['shortDetail'] ?? '';

        return str_contains($detail, 'TBD');
    }

    /**
     * @param  array<int, string>  $expressions
     */
    private function writeWindowsFile(array $expressions): void
    {
        $lines = implode("\n", array_map(fn (string $expr) => "    '{$expr}',", $expressions));

        $contents = <<<PHP
        <?php

        // Auto-generated by `php artisan schedule:generate-polling-windows` — do not
        // hand-edit. Regenerated weekly by .github/workflows/update-polling-windows.yml
        // from the real upcoming schedule and committed as a normal deploy (that's the
        // only way Laravel Cloud reliably picks up a changed wake schedule — see
        // routes/console.php for why). Each entry is a cron expression covering a
        // window where a game is plausibly live, pinned to the exact calendar date
        // rather than a guessed recurring weekly pattern.
        return [
        {$lines}
        ];

        PHP;

        file_put_contents(base_path('routes/polling-windows.php'), $contents);
    }
}
